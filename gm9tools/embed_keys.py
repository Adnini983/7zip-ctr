#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
embed_keys.py -- bake the public keystone keybase into DumpKeysCTR.lua.

The AES key set that 7-Zip CTR needs (slot0x03/0x18/0x1B/0x25/0x2C..0x3F and the
common keys) is identical on every console -- it is public keydata from 3dbrew.
Instead of asking the user to put aeskeydb.bin on the SD card, the GodMode9 Lua
script ships with that keybase embedded, so a single .lua file produces a
complete keystone tree; anything the console adds (console-unique keys) is
merged in on top.

Usage:
    python embed_keys.py <keystone_dir> [--lua DumpKeysCTR.lua]

    <keystone_dir> must contain  ctraes_retail\  and/or  ctraes_dev\
    with the loose "Name=HEX" .key files produced by aeskeys2ctr.

The script rewrites the block between the BEGIN/END markers in the .lua file.
"""

import os
import re
import sys

BEGIN = "-- BEGIN EMBEDDED KEYBASE (generated by gm9tools/embed_keys.py -- do not edit by hand)"
END = "-- END EMBEDDED KEYBASE"


def read_keys(folder, unit):
    out = []
    if not os.path.isdir(folder):
        return out
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith(".key"):
            continue
        path = os.path.join(folder, name)
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
        for line in text.splitlines():
            line = line.strip()
            if not line or "=" not in line:
                continue
            keyname, hexval = line.split("=", 1)
            hexval = re.sub(r"[^0-9a-fA-F]", "", hexval)
            if len(hexval) < 32:
                continue
            out.append((keyname.strip(), hexval[:32].upper(), unit))
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    root = sys.argv[1]
    lua = os.path.join(os.path.dirname(os.path.abspath(__file__)), "DumpKeysCTR.lua")
    i = 2
    while i < len(sys.argv):
        if sys.argv[i] == "--lua" and i + 1 < len(sys.argv):
            lua = sys.argv[i + 1]
            i += 2
        else:
            i += 1

    keys = read_keys(os.path.join(root, "ctraes_retail"), "retail")
    keys += read_keys(os.path.join(root, "ctraes_dev"), "dev")
    if not keys:
        print("no keys found under %s" % root, file=sys.stderr)
        return 1

    # de-duplicate on (name, unit), last wins
    seen = {}
    order = []
    for name, hexval, unit in keys:
        k = (name.lower(), unit)
        if k not in seen:
            order.append(k)
        seen[k] = (name, hexval, unit)
    entries = [seen[k] for k in order]

    body = []
    body.append(BEGIN)
    body.append("local EMBEDDED = {")
    for name, hexval, unit in entries:
        body.append('  { "%s", "%s", "%s" },' % (name, hexval, unit))
    body.append("}")
    body.append(END)

    with open(lua, "r", encoding="utf-8") as f:
        text = f.read()

    start = text.find(BEGIN)
    stop = text.find(END)
    if start < 0 or stop < 0:
        print("markers not found in %s" % lua, file=sys.stderr)
        return 1
    text = text[:start] + "\n".join(body) + text[stop + len(END):]
    with open(lua, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    retail = sum(1 for e in entries if e[2] == "retail")
    dev = len(entries) - retail
    print("embedded %d keys (%d retail, %d devkit) into %s"
          % (len(entries), retail, dev, lua))
    return 0


if __name__ == "__main__":
    sys.exit(main())
