#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
embed_keys.py -- bake the public keybase into DumpKeysCTR.lua, obfuscated.

The AES key set that 7-Zip CTR needs is public keydata (identical on every
console), so the GodMode9 script ships with it. To avoid storing key material as
readable plaintext inside a public repository, the keybase is packed as

    unit|KeyName|32-hex    (one key per line)
    -> XOR with 0xA5
    -> base64
    -> KEYBASE_B64 in the .lua, decoded at runtime

Usage:
    python embed_keys.py <keystone_dir> [--lua DumpKeysCTR.lua]

    <keystone_dir> must contain  ctraes_retail\  and/or  ctraes_dev\
    with the loose "Name=HEX" .key files produced by aeskeys2ctr.

The script rewrites the block between the BEGIN/END markers plus the small
decoder that follows them, so re-running it is safe.
"""

import base64
import os
import re
import sys

BEGIN = "-- BEGIN EMBEDDED KEYBASE (generated by gm9tools/embed_keys.py -- do not edit by hand)"
END = "-- END EMBEDDED KEYBASE"
MASK = 0xA5
CHUNK = 240

DECODER = r'''
-- The keybase above is packed (XOR 0xA5 + base64) so no key value sits in the
-- repository as readable text; it is public keydata, not a secret.
local function keybaseDecode(s)
  local map = {}
  local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
  for i = 1, 64 do
    map[alphabet:sub(i, i)] = i - 1
  end
  local out, acc, n = {}, 0, 0
  for i = 1, #s do
    local c = s:sub(i, i)
    if c == "=" then break end
    local v = map[c]
    if v then
      acc = acc * 64 + v
      n = n + 1
      if n == 4 then
        out[#out + 1] = string.char(
          math.floor(acc / 65536) % 256,
          math.floor(acc / 256) % 256,
          acc % 256)
        acc, n = 0, 0
      end
    end
  end
  if n == 2 then
    out[#out + 1] = string.char(math.floor(acc / 16) % 256)
  elseif n == 3 then
    out[#out + 1] = string.char(math.floor(acc / 4096) % 256, math.floor(acc / 16) % 256)
  end
  local raw = table.concat(out)
  local plain = {}
  for i = 1, #raw do
    plain[i] = string.char(raw:byte(i) ~ 0xA5)
  end
  return table.concat(plain)
end

local EMBEDDED = {}
do
  for line in keybaseDecode(KEYBASE_B64):gmatch("[^\n]+") do
    local unit, name, hex = line:match("^(%a+)|([^|]+)|(%x+)$")
    if unit and name and hex then
      EMBEDDED[#EMBEDDED + 1] = { name, hex, unit }
    end
  end
end
'''


def read_keys(folder, unit):
    out = []
    if not os.path.isdir(folder):
        return out
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith(".key"):
            continue
        with open(os.path.join(folder, name), "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
        for line in text.splitlines():
            line = line.strip()
            if not line or "=" not in line:
                continue
            keyname, hexval = line.split("=", 1)
            hexval = re.sub(r"[^0-9a-fA-F]", "", hexval)
            if len(hexval) < 32:
                continue
            out.append((keyname.strip(), hexval[:32].upper(), unit))
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    root = sys.argv[1]
    lua = os.path.join(os.path.dirname(os.path.abspath(__file__)), "DumpKeysCTR.lua")
    i = 2
    while i < len(sys.argv):
        if sys.argv[i] == "--lua" and i + 1 < len(sys.argv):
            lua = sys.argv[i + 1]
            i += 2
        else:
            i += 1

    keys = read_keys(os.path.join(root, "ctraes_retail"), "retail")
    keys += read_keys(os.path.join(root, "ctraes_dev"), "dev")
    if not keys:
        print("no keys found under %s" % root, file=sys.stderr)
        return 1

    seen, order = {}, []
    for name, hexval, unit in keys:
        k = (name.lower(), unit)
        if k not in seen:
            order.append(k)
        seen[k] = (name, hexval, unit)
    entries = [seen[k] for k in order]

    packed = "\n".join("%s|%s|%s" % (u, n, h) for n, h, u in entries)
    masked = bytes(b ^ MASK for b in packed.encode("ascii"))
    b64 = base64.b64encode(masked).decode("ascii")

    chunks = [b64[i:i + CHUNK] for i in range(0, len(b64), CHUNK)]
    body = [BEGIN, "local KEYBASE_B64 = table.concat({"]
    for c in chunks:
        body.append('  "%s",' % c)
    body.append('}, "")')
    body.append(END)
    body.append(DECODER)
    block = "\n".join(body)

    with open(lua, "r", encoding="utf-8") as f:
        text = f.read()

    start = text.find(BEGIN)
    if start < 0:
        print("markers not found in %s" % lua, file=sys.stderr)
        return 1
    # the block ends with the decoder's "end" that closes the EMBEDDED do-block
    tail = text.find("\nend\n", text.find(END, start))
    if tail < 0:
        print("decoder tail not found in %s" % lua, file=sys.stderr)
        return 1
    stop = tail + len("\nend\n")
    text = text[:start] + block + text[stop:]

    with open(lua, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    retail = sum(1 for e in entries if e[2] == "retail")
    print("embedded %d keys (%d retail, %d devkit), %d bytes base64, into %s"
          % (len(entries), retail, len(entries) - retail, len(b64), lua))
    return 0


if __name__ == "__main__":
    sys.exit(main())
