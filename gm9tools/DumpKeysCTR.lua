-- DumpKeysCTR.lua -- GodMode9 Lua script for 7-Zip CTR
--
-- Builds a READY-TO-USE keystone\ tree on the SD card: no PC-side conversion,
-- no manual hex copying. Compared to DumpKeysCTR.gm9 this one can slice files
-- (fs.read_file with an offset) and gets the console data from GodMode9 itself
-- (sys.serial / IS_DEVKIT / CONSOLE_TYPE), so everything lands in the final
-- layout the handler expects.
--
-- Output: 0:/gm9/out/7zctr-keys/
--   keystone/ctraes_retail/*.key        retail AES keys   (safe to publish)
--   keystone/ctraes_dev/*.key           devkit AES keys   (safe to publish)
--   keystone/pubkey/retail_firm_pubkey.bin
--   keystone/pubkey/dev_firm_pubkey.bin
--   keystone/pubkey/pubkey.ini
--   keystone/ctrdevice/<SERIAL>/boot9.bin
--   keystone/ctrdevice/<SERIAL>/otp.mem
--   keystone/ctrdevice/<SERIAL>/otp_dec.mem
--   keystone/ctrdevice/<SERIAL>_<unit>/boot9.bin
--   keystone/ctrdevice/<SERIAL>_<unit>/otp.mem
--   keystone/ctrdevice/<SERIAL>_<unit>/otp_dec.mem
--   keystone/ctrdevice/<SERIAL>_<unit>/nand_cid.mem
--   keystone/ctrdevice/<SERIAL>_<unit>/ctrindex.ini
--   seeddb.bin                          (only when a complete one is available)
--   README.txt
--   dump.log
--
-- HOW TO RUN
--   1. Put this file in 0:/gm9/luascripts/ and use HOME -> "Lua scripts..."
--      (or select it in the browser -> "Execute Lua script").
--   2. Copy 0:/gm9/out/7zctr-keys/keystone + seeddb.bin next to 7z.dll
--      (merge with the existing keystone folder).
--
-- Nothing has to be prepared on the SD card for keys: the public AES keybase is
-- embedded below and the FIRM moduli come out of boot9.bin. There is no separate
-- "private" folder because the handler never reads one -- console-unique keys go
-- into the same ctraes_retail / ctraes_dev folder as the rest.
--
-- seeddb.bin is the one item that cannot come from the console: a machine only
-- knows the seeds of its own installed titles. The script only copies a complete
-- database (0:/gm9/support/seeddb.bin, 0:/seeddb.bin or 0:/gm9/out/seeddb.bin)
-- and otherwise leaves it out with an explanation -- the release already ships
-- one next to 7z.dll.
--
-- Everything is ASCII on purpose: GodMode9's default font has no CJK glyphs.

